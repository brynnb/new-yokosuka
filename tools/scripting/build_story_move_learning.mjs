// Run before the ordinary investigation/combat compilers. No disc extraction.
import fs from 'node:fs';
import path from 'node:path';
import learning from '../../play/data/story-move-learning.json' with {type:'json'};
import {MARTIAL_ARTS_MOVES} from '../../src/MartialArtsCombat.js';
import {moveLearningRegions,moveLearningChallenges} from './story-move-learning.mjs';
const root=path.resolve(import.meta.dirname,'../..');
const server=process.env.NEW_YOKOSUKA_SERVER_DIR;
if(!server)throw Error('NEW_YOKOSUKA_SERVER_DIR is required');
const unique=new Set();
for(const move of learning.moves){
  if(unique.has(move.id)||!MARTIAL_ARTS_MOVES[move.id]||move.name.replaceAll(' ','')!==MARTIAL_ARTS_MOVES[move.id].label.replaceAll(' ','')||
    !/^[a-z]+(?:-[a-z]+)*$/.test(move.slug)||Boolean(move.teacher)===Boolean(move.itemKey))throw Error(`Invalid learning record ${move.id}`);
  unique.add(move.id);
}
const write=(file,value)=>fs.writeFileSync(file,JSON.stringify(value,null,2)+'\n');
for(const [file,key,records]of [['story_regions.json','regions',moveLearningRegions],['challenges.json','challenges',moveLearningChallenges]]){
  const target=path.join(server,'internal/scriptevent',file),data=JSON.parse(fs.readFileSync(target));
  const ids=new Set(records.map(r=>r.id));
  data[key]=[...data[key].filter(r=>!ids.has(r.id)),...records];
  const compact='{\n'+Object.entries(data).map(([name,value])=>'  '+JSON.stringify(name)+': '+
    (name===key?'[\n'+value.map(record=>'    '+JSON.stringify(record)).join(',\n')+'\n  ]':JSON.stringify(value))).join(',\n')+'\n}\n';
  fs.writeFileSync(target,compact);
  fs.writeFileSync(path.join(root,'play/data',file==='story_regions.json'?'story-regions.json':'story-challenges.json'),compact);
}
// Keep the existing registry's compact formatting; replace only these entries.
const registry=path.join(server,'internal/scriptcontent/commands.v1.json');
let source=fs.readFileSync(registry,'utf8');
const additions=[...moveLearningRegions.map(r=>({kind:'bounds',identifier:r.id,description:'Authored optional move/scroll approach.'})),
  ...moveLearningChallenges.map(r=>({kind:'challenge',identifier:r.id,description:'Shared client combat lesson; acknowledged success learns one move.'}))];
for(const entry of additions){
  const lines=source.split('\n'),index=lines.findIndex(line=>{
    try{const value=JSON.parse(line.trim().replace(/,$/,''));return value.kind===entry.kind&&value.identifier===entry.identifier;}catch{return false;}
  });
  if(index>=0)lines.splice(index,1);
  source=lines.join('\n');
}
source=source.replace(/("capabilities":\s*\[)/,`$1\n${additions.map(e=>'    '+JSON.stringify(e)+',').join('\n')}`);
JSON.parse(source);
fs.writeFileSync(registry,source);
write(path.join(server,'internal/store/move_scrolls.json'),learning.moves.filter(m=>m.itemKey).map(m=>({
  itemKey:m.itemKey,moveId:m.id,flag:`story.s1.${m.slug}.learned`,...(m.requiredFlag?{requiredFlag:m.requiredFlag}:{})})));
const sqlQuote=s=>"'"+s.replaceAll("'","''")+"'";
const rows=learning.moves.filter(m=>m.itemKey).map(m=>`(${sqlQuote(m.itemKey)},${sqlQuote(m.name+' Scroll')},${sqlQuote(m.requiredFlag?'A Chinese move scroll. Ask Master Chen to translate it, then read it in Story mode.':'Read this move scroll in Story mode to learn '+m.name+'.')},'move_scroll',1,true,'learn_move',0)`);
fs.writeFileSync(path.join(server,'internal/store/migrations/015_story_move_scrolls.sql'),
  '-- Generated by tools/scripting/build_story_move_learning.mjs in the client repository.\nINSERT INTO item_definitions (key,name,description,category,max_stack,usable,effect_kind,effect_value)\nVALUES\n'+rows.join(',\n')+';\n');
console.log(`Prepared ${moveLearningChallenges.length} optional lessons and ${rows.length} scroll definitions.`);
